import math


def arco(cx, cy, rx, ry, a0, a1, n=24):
    return [
        (cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
         cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n)))
        for i in range(n + 1)
    ]


def girar(trazo):
    return [(1 - x, 1 - y) for x, y in trazo]


